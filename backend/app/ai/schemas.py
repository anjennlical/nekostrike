from typing import Annotated, Literal
from uuid import UUID
from datetime import datetime
from pydantic import BaseModel, ConfigDict, Field, field_validator, model_validator

Text = Annotated[str, Field(min_length=1, max_length=1800)]


class StrictModel(BaseModel):
    model_config = ConfigDict(extra="forbid", strict=True)


class AnalyzeInput(BaseModel):
    model_config = ConfigDict(extra="forbid")
    finding_id: UUID


class EvidenceReference(StrictModel):
    evidence_id: str = Field(min_length=1, max_length=100)
    path: str = Field(min_length=1, max_length=100)
    actor: str = Field(min_length=1, max_length=30)
    status: int = Field(ge=100, le=599)


class Analysis(StrictModel):
    finding_id: str = Field(min_length=36, max_length=36)
    summary: Text
    technical_explanation: Text
    potential_impact: Text
    evidence_used: list[EvidenceReference] = Field(min_length=3, max_length=3)
    recommendations: list[Text] = Field(min_length=1, max_length=6)
    limitations: list[Text] = Field(min_length=1, max_length=6)


class TokenUsage(StrictModel):
    input_tokens: int = Field(ge=0, le=9007199254740991)
    output_tokens: int = Field(ge=0, le=9007199254740991)
    total_tokens: int = Field(ge=0, le=9007199254740991)
    cached_tokens: int | None = Field(default=None, ge=0)
    reasoning_tokens: int | None = Field(default=None, ge=0)
    cache_write_tokens: int | None = Field(default=None, ge=0)

    @model_validator(mode="after")
    def consistent_counts(self):
        if self.total_tokens != self.input_tokens + self.output_tokens:
            raise ValueError("inconsistent total")
        if any(value is not None and value > self.input_tokens for value in (self.cached_tokens, self.cache_write_tokens)):
            raise ValueError("input detail exceeds input")
        if self.reasoning_tokens is not None and self.reasoning_tokens > self.output_tokens:
            raise ValueError("reasoning exceeds output")
        return self


class Consumption(StrictModel):
    # Provider metadata, never generated by the language model. No monetary estimate.
    usage: TokenUsage | None = None
    usage_status: Literal["reported", "not_provided", "invalid"] = "not_provided"
    service_tier: Literal["auto", "default", "flex", "scale", "priority", "fast", "ultrafast"] | None = None
    reported_model: str | None = Field(default=None, min_length=1, max_length=100, pattern=r"^[a-zA-Z0-9._:-]+$")

    @model_validator(mode="after")
    def consistent_status(self):
        if (self.usage is not None) != (self.usage_status == "reported"):
            raise ValueError("inconsistent usage status")
        return self


class AnalysisRecord(StrictModel):
    id: str = Field(pattern=r"^[0-9a-f-]{36}$")
    created_at: str = Field(max_length=40)
    review_status: Literal["pending", "reviewed"] = "pending"
    # Legacy field retained for compatibility. New metadata lives in result.consumption.
    usage: None = None
    run_id: str | None = None
    check_type: Literal["bola", "data_exposure", "security_misconfiguration"] | None = None
    evidence_status: Literal["current", "historical"] = "current"

    @field_validator("run_id")
    @classmethod
    def valid_run(cls, value):
        if value is not None:
            UUID(value)
        return value

    @field_validator("id")
    @classmethod
    def valid_id(cls, value):
        UUID(value)
        return value

    @field_validator("created_at")
    @classmethod
    def valid_time(cls, value):
        if datetime.fromisoformat(value).utcoffset() is None:
            raise ValueError("timezone required")
        return value


class AnalysisResult(StrictModel):
    # Missing in legacy JSON means version 1; unknown versions fail closed.
    format_version: Literal[1] = 1
    analysis: Analysis
    provider: Literal["openai", "test_double"]
    model: str = Field(min_length=1, max_length=200)
    cached: bool
    requires_human_review: Literal[True] = True
    # These fields are supplied by the server, NEVER by the model.
    deterministic_verdict: Literal["vulnerable"]
    deterministic_severity: Literal["high", "medium"]
    record: AnalysisRecord | None = None
    storage_warning: bool = False
    consumption: Consumption | None = None

    @field_validator("format_version", mode="before")
    @classmethod
    def supported_format(cls, value):
        if type(value) is not int or value != 1:
            raise ValueError("unsupported analysis format")
        return value


class AIStatus(StrictModel):
    status: Literal["disabled", "missing_key", "missing_model", "invalid_config", "configured"]
    provider: Literal["openai", "test_double"] = "openai"
    model: str | None
    requests_remaining: int
    max_output_tokens: int
    timeout_seconds: int
    provider_verified: Literal[False] = False
